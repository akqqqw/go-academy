// Проверка схемы Supabase на безопасность (RLS).
//
// Это статический контракт-тест: он читает SQL-файлы, которые применяются к
// боевой базе, и падает, если новая таблица появилась без RLS, политики
// владельца или с грантом для роли `anon`. Живая база здесь не нужна — такие
// проверки выполняются в SQL-редакторе Supabase по инструкции
// docs/DATABASE.md, раздел 5.
import { readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { describe, expect, it } from 'vitest'

const here = dirname(fileURLToPath(import.meta.url))
const databaseDir = resolve(here, '../../../backend/internal/database')
const pgSchema = readFileSync(resolve(databaseDir, 'schema_pg.sql'), 'utf8')
const sqliteSchema = readFileSync(resolve(databaseDir, 'schema_sqlite.sql'), 'utf8')

function tablesOf(sql: string): string[] {
  return [...sql.matchAll(/CREATE TABLE IF NOT EXISTS (\w+)/g)].map((match) => match[1]!)
}

const tables = tablesOf(pgSchema)

describe('схема Postgres', () => {
  it('содержит все таблицы приложения', () => {
    expect(tables).toEqual(
      expect.arrayContaining([
        'user_profiles',
        'settings',
        'activity_days',
        'lessons',
        'exercises',
        'code_runs',
        'code_drafts',
        'notes',
        'note_tags',
        'note_folders',
        'flashcards',
        'card_reviews',
        'quiz_attempts',
        'exercise_attempts',
        'achievements',
      ]),
    )
  })

  it('включает RLS для каждой пользовательской таблицы', () => {
    const missing = tables.filter(
      (table) => !new RegExp(`ALTER TABLE ${table} ENABLE ROW LEVEL SECURITY;`).test(pgSchema),
    )
    expect(missing).toEqual([])
  })

  it('ограничивает строки владельцем через auth.uid()', () => {
    const missing = tables.filter((table) => {
      const pattern = new RegExp(
        `CREATE POLICY \\w+ ON ${table} FOR ALL TO authenticated\\s+` +
          'USING \\(user_id = auth\\.uid\\(\\)\\) WITH CHECK \\(user_id = auth\\.uid\\(\\)\\);',
      )
      return !pattern.test(pgSchema)
    })
    expect(missing).toEqual([])
  })

  it('не выдаёт роль anon никаких прав', () => {
    expect(pgSchema).not.toMatch(/GRANT[^;]*TO anon/i)
    expect(pgSchema).not.toMatch(/CREATE POLICY[\s\S]{0,200}TO anon/i)
  })

  it('оставляет schema_migrations только для чтения', () => {
    expect(pgSchema).toMatch(/REVOKE ALL ON TABLE schema_migrations FROM authenticated;/)
    expect(pgSchema).toMatch(/GRANT SELECT ON TABLE schema_migrations TO authenticated;/)
  })

  it('каждая таблица привязана к пользователю', () => {
    const blocks = pgSchema.split(/CREATE TABLE IF NOT EXISTS /).slice(1)
    expect(blocks).toHaveLength(tables.length)
    for (const block of blocks) {
      const name = /^(\w+)/.exec(block)?.[1] ?? ''
      const body = block.slice(0, block.indexOf(');'))
      expect(body, `таблица ${name} без user_id`).toMatch(/user_id\s+uuid/)
    }
  })

  it('совпадает по составу таблиц со схемой SQLite', () => {
    const sqliteTables = tablesOf(sqliteSchema)
    expect(sqliteTables.sort()).toEqual([...tables].sort())
  })
})

describe('схема SQLite для тестов', () => {
  it('не содержит Postgres-специфичных конструкций', () => {
    expect(sqliteSchema).not.toMatch(/auth\.uid\(\)/)
    expect(sqliteSchema).not.toMatch(/GENERATED BY DEFAULT AS IDENTITY/)
  })
})
